"""Generate app/themes.css. globals.css uses tokens instead of fixed colors: --n-<hex> for neutrals (backgrounds,
borders, text) and --s-<hex> for bright text colors; each theme maps them from the original dark-theme color.
Usage: python3 scripts/themes.py > app/themes.css"""
import colorsys
import json
from pathlib import Path

HERE = Path(__file__).parent
neutral = json.load(open(HERE / 'theme_neutrals.json'))
N, N_RGB = neutral['neutral'], set(neutral['rgb'])
SAT = json.load(open(HERE / 'theme_saturated.json'))


def hls(c): return colorsys.rgb_to_hls(*(v / 255 for v in c))
def to_hex(h, l, s): return '#%02x%02x%02x' % tuple(round(max(0, min(1, v)) * 255) for v in colorsys.hls_to_rgb(h, max(0, min(1, l)), max(0, min(1, s))))
def rgb_of(hexv): return ' '.join(str(int(hexv[i:i + 2], 16)) for i in (1, 3, 5))


# neutral(h, l, s) -> (h, l, s); light themes invert lightness so text stays readable on bright backgrounds.
THEMES = {
    'dark': (lambda h, l, s: (h, l, s), 'dark'),
    # Light themes: dark backgrounds and borders (l < .3) become light ones; gray text (l >= .3) maps to .47-.1, dark
    # enough for 4.5:1 on the page.
    'light': (lambda h, l, s: (h, .985 - l * .93 if l < .3 else .47 - (l - .3) * .53, min(s, .18)), 'light'),
    'midnight': (lambda h, l, s: (.62, l * 1.05 + .01, min(1, s + .35)), 'dark'),
    'oled': (lambda h, l, s: (h, l * .45 if l < .5 else l, s), 'dark'),
    'paper': (lambda h, l, s: (.11, .975 - l * .9 if l < .3 else .44 - (l - .3) * .5, .28 if l < .3 else .22), 'light'),
}

print('/* Generated by scripts/themes.py: do not edit by hand. */')
for name, (fn, scheme) in THEMES.items():
    light = scheme == 'light'
    vals = {k: to_hex(*fn(*hls(c))) for k, c in N.items()}
    decl = [f'--n-{k}:{v}' for k, v in vals.items()] + [f'--n-{k}-rgb:{rgb_of(vals[k])}' for k in sorted(N_RGB)]
    for k, c in SAT.items():
        h, l, s = hls(c)
        # Bright text on a light page: same hue, dark enough to read (about 4.5:1 on white).
        v = to_hex(h, min(l, .32), max(s, .65)) if light else '#' + k
        decl += [f'--s-{k}:{v}', f'--s-{k}-rgb:{rgb_of(v)}']
    decl.append('--bg-rgb:' + rgb_of(vals['08080c']).replace(' ', ','))
    decl.append('--fg-rgb:' + ('20,20,30' if light else '255,255,255'))
    decl.append('--on-accent:' + ('#ffffff' if light else '#0a0a0f'))
    decl.append('color-scheme:' + scheme)
    print((':root' if name == 'dark' else f':root[data-theme="{name}"]') + '{' + ';'.join(decl) + '}')
